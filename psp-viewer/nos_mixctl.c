static const uint32_t residual_mask[12]={0u,1u,3u,7u,15u,31u,63u,127u,255u,511u,1023u,2047u};
static uint16_t asin_binary(float input) {
    int negative=input<0;float a=fabsf(input);
    if(a>=1)return negative?0xc000u:0x4000u;
    unsigned fixed=(unsigned)(a*65536.f),band=0,span=32768u,upper=32768u;
    if(fixed>=32768u)for(unsigned n=0;n<11;n++){
        span>>=1;band++;upper+=span;if(fixed<upper)break;
    }
    unsigned low=upper-span,slot=(fixed-low)>>(11u-band),index=band*16u+slot;
    if(index>=209u)index=208u;
    float anchor=(float)(low+slot*(span>>4))*(1.f/65536.f);
    int fraction=(int)(((a-anchor)*asin_lut[index].slope)*65536.f);
    uint16_t result=(uint16_t)(asin_lut[index].base+fraction);
    return negative?(uint16_t)(0u-result):result;
}
static int db_from_q15(unsigned value) {
    if(!value)return -10000;
    if(value>32767u)value=32767u;
    unsigned shift=0;while(!(value&(16384u>>shift)))shift++;
    unsigned residual=value-(16384u>>shift);
    unsigned index=shift<5?residual>>(5-shift):(residual<<(shift-5))|residual_mask[shift-5];
    if(index>511u)index=511u;
    int result=q15_to_db[index]-(int)(shift+1)*602;
    return result< -10000?-10000:result;
}
static int q15_from_db(int db) {
    if(db>=0)return 32767;
    unsigned loss=(unsigned)(-db),shift=loss/602u,remainder=loss%602u;
    if(shift>=31)return 0;
    int result=db_to_q15[601u-remainder]>>shift;
    return result<50?0:result;
}
static unsigned curve_squared(unsigned q) {
    unsigned at=q>>6,fraction=((q&31u)<<9)|1023u;
    int a=cos_lut[at];
    if(a)a+=(int)(((int64_t)(cos_lut[at+1]-a)*fraction)>>15);
    return (unsigned)(((int64_t)a*a)>>15);
}
int nos_mixctl_chase_options(NosMixCtl *out,float dx,float dz,float fx,float fz,int drag,unsigned sfx_option_q15) {
    if(sfx_option_q15>32767u||!out||!isfinite(dx)||!isfinite(dz)||!isfinite(fx)||!isfinite(fz))return 0;
    float direction=hypotf(fx,fz),distance=hypotf(dx,dz);
    if(!(direction>0.000007071068f)||!isfinite(direction)||!isfinite(distance)||distance>100000000.f)return 0;
    NosMixCtl next={0};
    next.distance_m=(int32_t)distance;
    if(distance>0.000007071068f){
        float nx=dx/distance,nz=dz/distance,cx=fx/direction,cz=fz/direction;
        float dot=nx*cx+nz*cz;if(dot>1)dot=1;if(dot< -1)dot=-1;
        uint16_t angle=(uint16_t)(0x4000-(int16_t)asin_binary(dot));
        /* Original axes are GameX=GUz, GameY=GUx. This cross is the
         * SetCameraAngle sign test after that coordinate mapping. */
        if(nz*cx-nx*cz<0)angle=(uint16_t)~angle;
        next.azimuth=angle;
    }
    int d=next.distance_m;
    next.distance_q15=d<=10?0:d>=130?32767:(int)(((float)(d-10)/120.f)*32767.f);
    unsigned q=(unsigned)next.distance_q15,amp=curve_squared(q),angle_part=next.azimuth&16383u;
    unsigned blended=(unsigned)(((uint64_t)amp*(32767u-2u*angle_part))>>15);
    if(angle_part)blended+=(unsigned)(((uint64_t)amp*(2u*angle_part))>>15);
    next.spatial_db100=db_from_q15(blended);
    int base=drag?-775:-1075;
    /* SFXCTL_MasterVol80096ca0 at original Master1, then DataProc shape8
     * and NFSMixCtl800b1cc8 with dbDown=-10000/unity scale. Keep these
     * quantizers before graph gating; a postmix mute cannot substitute. */
    float option=(float)sfx_option_q15/32767.f;
    int curve=cos_lut[0]+(int)(((int64_t)(cos_lut[1]-cos_lut[0])*1023)>>15);
    float master_curve=(float)curve/32767.f;
    int inverse=(int)((1.f-option*master_curve)*32767.f);
    int data_q15=32767-inverse;
    unsigned ctl_q15=32767u-(unsigned)(((int64_t)(32767-data_q15)*32767)>>15);
    int option_db=(db_from_q15(ctl_q15)*32767)>>15;
    int fixed=base+option_db;
    if(fixed<base-10000)fixed=base-10000;
    if(fixed> -base)fixed= -base;
    next.nos_q15=q15_from_db(fixed+next.spatial_db100-200);
    next.purge_q15=q15_from_db(fixed+next.spatial_db100-750);
    *out=next;return 1;
}

int nos_mixctl_chase(NosMixCtl *out,float dx,float dz,float fx,float fz,int drag) {
    return nos_mixctl_chase_options(out,dx,dz,fx,fz,drag,32767u);
}

/* PS2 SLUS_210.65 MAPOUTPUT{,DFT,DRG,URL}: collision state5/channel2,
 * output7/8 trim -300. Spatial2 has one default camera entry90051002:
 * car distance/car azimuth, curve4 in all quadrants, near4, far70/40/30/40.
 * The common subchannel's two envelopes are triggered by car/world flags;
 * neither is triggered by the prop flag. Its remaining input is SFX option.
 * Shares the verified retail GC quantizer tables above, not NOS geometry. */
static unsigned glass_curve4(unsigned q) {
    unsigned at=q>>6,fraction=((q&31u)<<9)|1023u;
    int a=cos_lut[511u-at],b=cos_lut[512u-at];
    return (unsigned)(32767-a+(int)(((int64_t)(a-b)*fraction)>>15));
}
int glass_mixctl_ps2(GlassMixCtl *out,float dx,float dz,float fx,float fz,int mode,unsigned option) {
    if(!out || mode<0 || mode>3 || option>32767u || !isfinite(dx) || !isfinite(dz) || !isfinite(fx) || !isfinite(fz))return 0;
    float direction=hypotf(fx,fz),distance=hypotf(dx,dz);
    if(!(direction>0.000007071068f) || !isfinite(direction) || !isfinite(distance) || distance>100000000.f)return 0;
    GlassMixCtl next={0};next.distance_m=(int32_t)distance;
    if(distance>0.000007071068f) {
        float dot=(dx*fx+dz*fz)/(distance*direction);if(dot>1)dot=1;if(dot< -1)dot=-1;
        next.azimuth=(uint16_t)(0x4000-(int16_t)asin_binary(dot));
        if(dz*fx-dx*fz<0)next.azimuth=(uint16_t)~next.azimuth;
    }
    static const int far[4]={70,40,30,40};
    unsigned quadrant=next.azimuth>>14,part=next.azimuth&16383u,amp[2];
    for(unsigned j=0;j<2;j++) {
        int end=far[(quadrant+j)&3u],d=next.distance_m;
        unsigned q=d<=4?0u:d>=end?32767u:(unsigned)(((float)(d-4)/(float)(end-4))*32767.f);
        amp[j]=glass_curve4(q);
    }
    /* GetAzimShapeOutput keeps the two separately truncated products. */
    unsigned spatial=(unsigned)(((uint64_t)amp[0]*(32767u-2u*part))>>15);
    if(part)spatial+=(unsigned)(((uint64_t)amp[1]*(2u*part))>>15);
    next.spatial_db100=db_from_q15(spatial);
    next.gain_q15=glass_mixctl_gain_ps2(next.spatial_db100,mode,option);
    *out=next;return 1;
}

int glass_mixctl_gain_ps2(int spatial_db100,int mode,unsigned option) {
    if(mode<0 || mode>3 || option>32767u || spatial_db100< -32768 || spatial_db100>0)return 0;
    static const int base[4]={-300,-500,100,-300};
    /* Same global SFX Master1 source path as the NOS channel above. The
     * final Master bus stays outside; do not apply SFX again in the mixer. */
    float curve=(float)(cos_lut[0]+(int)(((int64_t)(cos_lut[1]-cos_lut[0])*1023)>>15))/32767.f;
    int inverse=(int)((1.f-((float)option/32767.f)*curve)*32767.f);
    unsigned ctl=32767u-(unsigned)(((int64_t)inverse*32767)>>15);
    int option_db=(db_from_q15(ctl)*32767)>>15;
    int fixed=base[mode]+option_db;
    if(fixed<base[mode]-10000)fixed=base[mode]-10000;
    /* InitChannel sign-extends the lower bound but keeps dBUP unsigned. */
    int upper=mode==2?65436:-base[mode];
    if(fixed>upper)fixed=upper;
    return q15_from_db(fixed+spatial_db100-300);
}
