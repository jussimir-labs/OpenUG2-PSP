#ifndef PROFILE_TRANSITION_DIAG_H
#define PROFILE_TRANSITION_DIAG_H
#include <stdint.h>

/* Opt-in transition evidence. No name, save payload or pointer is recorded. */
enum ProfileTransitionPhase {
    PD_SAVE_BEGIN=1, PD_SAVE_END, PD_CAREER_ENTER, PD_CARLOT_BEGIN, PD_CARLOT_END,
    PD_FRONT_CLOSE_BEGIN, PD_FRONT_CLOSE_END, PD_PLAYER_BEGIN, PD_PLAYER_END,
    PD_MODE_BEGIN, PD_MODE_END, PD_SHOP_EXIT_BEGIN, PD_SHOP_EXIT_END,
    PD_MOVIE_CHECK, PD_MOVIE_BEGIN, PD_MOVIE_END, PD_WORLD_BEGIN, PD_WORLD_END,
    PD_STREET_READY, PD_EXIT_BEGIN, PD_THREADS_BEGIN, PD_THREADS_END, PD_EXIT_FINAL,
    PD_MODEL_READ_GOT, PD_MODEL_READ_FLAGS, PD_MODEL_READ_ERRNO, PD_MODEL_READ_POSITION,
    PD_MODEL_RETRY_BEGIN, PD_MODEL_RETRY_END
};
enum { PROFILE_DIAG_MAGIC=0x4450324e, PROFILE_DIAG_VERSION=1, PROFILE_DIAG_WORDS=16, PROFILE_DIAG_LIMIT=32 };
typedef struct { uint32_t word[PROFILE_DIAG_WORDS]; } ProfileTransitionRecord;
_Static_assert(sizeof(ProfileTransitionRecord)==64,"profile transition record ABI");
#endif
